CREATE TABLE IF NOT EXISTS attendance (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_name TEXT REFERENCES employees(name) ON DELETE CASCADE,
  date DATE NOT NULL,
  check_in_at TIMESTAMPTZ,
  check_in_lat DOUBLE PRECISION,
  check_in_lng DOUBLE PRECISION,
  check_out_at TIMESTAMPTZ,
  check_out_lat DOUBLE PRECISION,
  check_out_lng DOUBLE PRECISION,
  is_late BOOLEAN DEFAULT false,
  late_minutes INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (employee_name, date)
);

ALTER TABLE office_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE attendance ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public Read" ON office_settings FOR SELECT USING (true);
CREATE POLICY "Public Write" ON office_settings FOR ALL USING (true);
CREATE POLICY "Public Read" ON attendance FOR SELECT USING (true);
CREATE POLICY "Public Write" ON attendance FOR ALL USING (true);
