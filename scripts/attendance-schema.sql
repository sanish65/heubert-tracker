-- ATTENDANCE SYSTEM SCHEMA
-- Apply manually via the Supabase SQL editor (this project has no migration runner).

-- Singleton office/attendance configuration, admin-editable from either app
CREATE TABLE IF NOT EXISTS office_settings (
  id BIGINT PRIMARY KEY DEFAULT 1,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  radius_meters INT NOT NULL DEFAULT 200,
  late_fine_amount NUMERIC NOT NULL DEFAULT 50,
  sync_time TEXT NOT NULL DEFAULT '09:30', -- HH:MM, Asia/Kathmandu
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT single_row CHECK (id = 1)
);

