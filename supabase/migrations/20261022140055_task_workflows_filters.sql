ALTER TABLE public.task_statuses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.task_filters ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Employees read statuses" ON public.task_statuses;
DROP POLICY IF EXISTS "Admins write statuses" ON public.task_statuses;
CREATE POLICY "Employees read statuses" ON public.task_statuses
  FOR SELECT USING (public.app_is_active_employee());
CREATE POLICY "Admins write statuses" ON public.task_statuses
  FOR ALL USING (public.app_is_admin()) WITH CHECK (public.app_is_admin());

DROP POLICY IF EXISTS "Read own or shared filters" ON public.task_filters;
DROP POLICY IF EXISTS "Create own filters" ON public.task_filters;
DROP POLICY IF EXISTS "Update own filters" ON public.task_filters;
DROP POLICY IF EXISTS "Owner or admin delete filters" ON public.task_filters;
CREATE POLICY "Read own or shared filters" ON public.task_filters
  FOR SELECT USING (
    public.app_is_active_employee()
    AND (shared OR owner_id = (public.app_current_employee()).id)
  );
CREATE POLICY "Create own filters" ON public.task_filters
  FOR INSERT WITH CHECK (public.app_is_active_employee() AND owner_id = (public.app_current_employee()).id);
CREATE POLICY "Update own filters" ON public.task_filters
  FOR UPDATE USING (owner_id = (public.app_current_employee()).id)
  WITH CHECK (owner_id = (public.app_current_employee()).id);
CREATE POLICY "Owner or admin delete filters" ON public.task_filters
  FOR DELETE USING (owner_id = (public.app_current_employee()).id OR (shared AND public.app_is_admin()));
