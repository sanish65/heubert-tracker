-- CUSTOM WORKFLOWS AND SAVED FILTERS
-- On top of 20261021170648_jira_more.sql (applied).
--
-- 1. Each project gets its own statuses (its board columns), each in one of Jira's three
--    categories: to do, in progress, done. "Done" everywhere (completed_at, sprint
--    completion, points done) now means "a status in the done category", not the word
--    'done'. Every existing project gets today's four statuses with today's keys, so no
--    issue changes.
-- 2. Saved filters: a name and a query (the JQL-like text the Tasks tab understands),
--    private to their owner or shared with the team.
--
-- Rules:
--   * Statuses -> employees read; admins add, rename, reorder and remove them
--   * Filters  -> you read yours and shared ones; you change and delete yours; admins
--                 may delete any shared filter

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Statuses per project
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.task_statuses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  -- The value stored in tasks.status. Never changes once made; the name can.
  key TEXT NOT NULL CHECK (key ~ '^[a-z][a-z0-9_]{0,39}$'),
  name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 40),
  category TEXT NOT NULL CHECK (category IN ('todo', 'progress', 'done')),
  sort_order INTEGER NOT NULL DEFAULT 0,
  -- Transitions: the statuses an issue in this one may move to next. NULL means any,
  -- which is how every status starts.
  allowed_next TEXT[],
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (project_id, key)
);

CREATE INDEX IF NOT EXISTS task_statuses_project_idx ON public.task_statuses (project_id, sort_order);

-- Today's workflow, for every project that exists and every project made from now on.
CREATE OR REPLACE FUNCTION private.seed_task_statuses(p_project_id BIGINT)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $$
  INSERT INTO public.task_statuses (project_id, key, name, category, sort_order)
  VALUES
    (p_project_id, 'todo', 'To Do', 'todo', 0),
    (p_project_id, 'in_progress', 'In Progress', 'progress', 1),
    (p_project_id, 'review', 'In Review', 'progress', 2),
    (p_project_id, 'done', 'Done', 'done', 3)
  ON CONFLICT (project_id, key) DO NOTHING;
$$;

SELECT private.seed_task_statuses(id) FROM public.projects;

CREATE OR REPLACE FUNCTION public.projects_seed_statuses()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  PERFORM private.seed_task_statuses(NEW.id);
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS projects_seed_statuses ON public.projects;
CREATE TRIGGER projects_seed_statuses
  AFTER INSERT ON public.projects
  FOR EACH ROW EXECUTE FUNCTION public.projects_seed_statuses();

-- Whether a status is in the done category for a project. Before a project has statuses
-- (it never should after this migration) the word 'done' still counts.
CREATE OR REPLACE FUNCTION public.task_status_is_done(p_project_id BIGINT, p_status TEXT)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT COALESCE(
    (SELECT category = 'done' FROM public.task_statuses WHERE project_id = p_project_id AND key = p_status),
    p_status = 'done'
  );
$$;

-- tasks.status is no longer one of four fixed words; tasks_workflow checks it against
-- the project's own statuses instead.
ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_status_check;

-- Runs after tasks_before_write (triggers of the same timing fire in name order), so it
-- has the final say on completed_at.
CREATE OR REPLACE FUNCTION public.tasks_workflow()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  was_done BOOLEAN := false;
  is_done BOOLEAN;
  arriving BOOLEAN;
  wanted_category TEXT;
  mapped TEXT;
  next_allowed TEXT[];
BEGIN
  IF NEW.project_id IS NULL THEN
    RETURN NEW;
  END IF;

  -- A new issue, or one filed into or moved to this project, may carry a status this
  -- workflow doesn't have (the old default 'todo', or another project's status). It lands
  -- in this project's first status of the same category instead.
  arriving := TG_OP = 'INSERT' OR OLD.project_id IS DISTINCT FROM NEW.project_id;
  IF NOT EXISTS (SELECT 1 FROM public.task_statuses WHERE project_id = NEW.project_id AND key = NEW.status) THEN
    IF arriving THEN
      IF TG_OP = 'UPDATE' AND OLD.project_id IS NOT NULL THEN
        SELECT category INTO wanted_category FROM public.task_statuses
        WHERE project_id = OLD.project_id AND key = OLD.status;
      END IF;
      wanted_category := COALESCE(wanted_category, CASE NEW.status
        WHEN 'todo' THEN 'todo' WHEN 'in_progress' THEN 'progress' WHEN 'review' THEN 'progress' WHEN 'done' THEN 'done' END);
      SELECT key INTO mapped FROM public.task_statuses
      WHERE project_id = NEW.project_id AND category = wanted_category
      ORDER BY sort_order, id LIMIT 1;
    END IF;
    IF mapped IS NULL THEN
      RAISE EXCEPTION 'Status "%" is not part of this project''s workflow', NEW.status;
    END IF;
    NEW.status := mapped;
  END IF;

  -- Transitions: a status may list where its issues can go next. A status that no
  -- longer exists, or lists nothing, allows any move.
  IF TG_OP = 'UPDATE' AND NEW.status IS DISTINCT FROM OLD.status AND NOT arriving
     AND COALESCE(current_setting('app.skip_transitions', true), 'off') <> 'on' THEN
    SELECT allowed_next INTO next_allowed FROM public.task_statuses
    WHERE project_id = NEW.project_id AND key = OLD.status;
    IF next_allowed IS NOT NULL AND NOT (NEW.status = ANY (next_allowed)) THEN
      RAISE EXCEPTION 'The workflow doesn''t allow moving from "%" to "%"',
        (SELECT name FROM public.task_statuses WHERE project_id = NEW.project_id AND key = OLD.status),
        (SELECT name FROM public.task_statuses WHERE project_id = NEW.project_id AND key = NEW.status);
    END IF;
  END IF;

  is_done := public.task_status_is_done(NEW.project_id, NEW.status);
  IF TG_OP = 'UPDATE' THEN
    was_done := public.task_status_is_done(OLD.project_id, OLD.status);
  END IF;

  IF is_done THEN
    NEW.completed_at := CASE WHEN was_done THEN COALESCE(OLD.completed_at, now()) ELSE now() END;
  ELSE
    NEW.completed_at := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS tasks_workflow ON public.tasks;
CREATE TRIGGER tasks_workflow
  BEFORE INSERT OR UPDATE ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.tasks_workflow();

-- A status can only be removed once no issue uses it, and a project keeps at least one
-- to-do and one done status, so new issues and "Done" always mean something. While
-- save_task_workflow runs, it checks the finished workflow as a whole instead (so two
-- statuses can swap categories).
CREATE OR REPLACE FUNCTION public.task_statuses_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  remaining INTEGER;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.key IS DISTINCT FROM OLD.key OR NEW.project_id IS DISTINCT FROM OLD.project_id THEN
      RAISE EXCEPTION 'A status''s key and project can''t change; rename it instead';
    END IF;
    IF NEW.category = OLD.category OR OLD.category NOT IN ('todo', 'done')
       OR COALESCE(current_setting('app.workflow_saving', true), 'off') = 'on' THEN
      RETURN NEW;
    END IF;
  ELSE
    -- The whole project is going (cascade): nothing to protect.
    IF NOT EXISTS (SELECT 1 FROM public.projects WHERE id = OLD.project_id) THEN
      RETURN OLD;
    END IF;
    IF EXISTS (SELECT 1 FROM public.tasks WHERE project_id = OLD.project_id AND status = OLD.key) THEN
      RAISE EXCEPTION 'Move the issues in "%" to another status first', OLD.name;
    END IF;
    IF OLD.category NOT IN ('todo', 'done') OR COALESCE(current_setting('app.workflow_saving', true), 'off') = 'on' THEN
      RETURN OLD;
    END IF;
  END IF;

  SELECT count(*) INTO remaining FROM public.task_statuses
  WHERE project_id = OLD.project_id AND category = OLD.category AND id <> OLD.id;
  IF remaining = 0 THEN
    RAISE EXCEPTION 'A workflow needs at least one % status', CASE OLD.category WHEN 'todo' THEN 'to-do' ELSE 'done' END;
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

-- A removed status leaves the other statuses' transition lists; a list it empties goes
-- back to "any", so no issue is left with nowhere to move.
CREATE OR REPLACE FUNCTION public.task_statuses_forget()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  UPDATE public.task_statuses
  SET allowed_next = NULLIF(array_remove(allowed_next, OLD.key), '{}')
  WHERE project_id = OLD.project_id AND OLD.key = ANY (allowed_next);
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS task_statuses_guard ON public.task_statuses;
CREATE TRIGGER task_statuses_guard
  BEFORE UPDATE OR DELETE ON public.task_statuses
  FOR EACH ROW EXECUTE FUNCTION public.task_statuses_guard();

DROP TRIGGER IF EXISTS task_statuses_forget ON public.task_statuses;
CREATE TRIGGER task_statuses_forget
  AFTER DELETE ON public.task_statuses
  FOR EACH ROW EXECUTE FUNCTION public.task_statuses_forget();

-- Moving every issue from one status to another in one go, before removing a status.
CREATE OR REPLACE FUNCTION public.move_task_status(p_project_id BIGINT, p_from TEXT, p_to TEXT)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  moved INTEGER;
BEGIN
  IF NOT public.app_is_admin() THEN
    RAISE EXCEPTION 'Only admins can change a workflow';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.task_statuses WHERE project_id = p_project_id AND key = p_to) THEN
    RAISE EXCEPTION 'Status "%" is not part of this project''s workflow', p_to;
  END IF;
  -- An admin re-homing issues before removing a status isn't a workflow move, so the
  -- transition rules are set aside for this one statement.
  PERFORM set_config('app.skip_transitions', 'on', true);
  UPDATE public.tasks SET status = p_to WHERE project_id = p_project_id AND status = p_from;
  GET DIAGNOSTICS moved = ROW_COUNT;
  PERFORM set_config('app.skip_transitions', 'off', true);
  RETURN moved;
END;
$$;

-- The Board settings dialog saves a whole workflow in one go: every status in board
-- order (existing ones by id, new ones by the key the dialog chose), and where the issues
-- of each removed status go. All of it applies, or none of it does.
--   p_statuses: [{ "id": 12 | null, "key": "qa", "name": "In QA", "category": "progress",
--                  "allowed_next": ["done"] | null }, ...]
--   p_moves:    { "removed_key": "target_key", ... }
CREATE OR REPLACE FUNCTION public.save_task_workflow(p_project_id BIGINT, p_statuses JSONB, p_moves JSONB DEFAULT '{}'::jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  s JSONB;
  pos INTEGER := 0;
  kept BIGINT[] := '{}';
  final_keys TEXT[];
  next_keys TEXT[];
  new_id BIGINT;
  mv RECORD;
BEGIN
  IF NOT public.app_is_admin() THEN
    RAISE EXCEPTION 'Only admins can change a workflow';
  END IF;
  IF jsonb_typeof(p_statuses) IS DISTINCT FROM 'array' OR jsonb_array_length(p_statuses) = 0 THEN
    RAISE EXCEPTION 'A workflow needs at least one status';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.projects WHERE id = p_project_id) THEN
    RAISE EXCEPTION 'Project not found';
  END IF;

  -- One save at a time per project.
  PERFORM 1 FROM public.task_statuses WHERE project_id = p_project_id FOR UPDATE;

  SELECT array_agg(x->>'key') INTO final_keys FROM jsonb_array_elements(p_statuses) x;
  IF (SELECT count(DISTINCT k) FROM unnest(final_keys) k) <> cardinality(final_keys) THEN
    RAISE EXCEPTION 'Two statuses share a key';
  END IF;
  IF (SELECT count(DISTINCT lower(trim(x->>'name'))) FROM jsonb_array_elements(p_statuses) x) <> jsonb_array_length(p_statuses) THEN
    RAISE EXCEPTION 'Two statuses have the same name';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(p_statuses) x WHERE x->>'category' = 'todo') THEN
    RAISE EXCEPTION 'A workflow needs at least one to-do status';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(p_statuses) x WHERE x->>'category' = 'done') THEN
    RAISE EXCEPTION 'A workflow needs at least one done status';
  END IF;

  PERFORM set_config('app.workflow_saving', 'on', true);

  FOR s IN SELECT value FROM jsonb_array_elements(p_statuses) LOOP
    -- A transition list names other statuses of the finished workflow. One left with
    -- none is an error rather than quietly becoming "any status".
    next_keys := NULL;
    IF jsonb_typeof(s->'allowed_next') = 'array' THEN
      next_keys := ARRAY(
        SELECT DISTINCT v FROM jsonb_array_elements_text(s->'allowed_next') v
        WHERE v = ANY (final_keys) AND v <> s->>'key'
      );
      IF cardinality(next_keys) = 0 THEN
        RAISE EXCEPTION 'Choose where issues in "%" can move to', s->>'name';
      END IF;
    END IF;

    IF jsonb_typeof(s->'id') = 'number' THEN
      UPDATE public.task_statuses
      SET name = trim(s->>'name'), category = s->>'category', sort_order = pos, allowed_next = next_keys
      WHERE id = (s->>'id')::bigint AND project_id = p_project_id AND key = s->>'key';
      IF NOT FOUND THEN
        RAISE EXCEPTION 'The status "%" was changed elsewhere. Close Board settings and open it again.', s->>'name';
      END IF;
      kept := kept || (s->>'id')::bigint;
    ELSE
      IF EXISTS (SELECT 1 FROM public.task_statuses WHERE project_id = p_project_id AND key = s->>'key') THEN
        RAISE EXCEPTION 'The status "%" was added elsewhere. Close Board settings and open it again.', s->>'name';
      END IF;
      INSERT INTO public.task_statuses (project_id, key, name, category, sort_order, allowed_next)
      VALUES (p_project_id, s->>'key', trim(s->>'name'), s->>'category', pos, next_keys)
      RETURNING id INTO new_id;
      kept := kept || new_id;
    END IF;
    pos := pos + 1;
  END LOOP;

  -- Re-homing issues before their status goes isn't a workflow move: no transition rules.
  PERFORM set_config('app.skip_transitions', 'on', true);
  FOR mv IN SELECT key AS from_key, value AS to_key FROM jsonb_each_text(COALESCE(p_moves, '{}'::jsonb)) LOOP
    IF mv.from_key = ANY (final_keys) THEN
      CONTINUE;
    END IF;
    IF NOT (mv.to_key = ANY (final_keys)) THEN
      RAISE EXCEPTION 'Issues can only move to a status that stays in the workflow';
    END IF;
    UPDATE public.tasks SET status = mv.to_key WHERE project_id = p_project_id AND status = mv.from_key;
  END LOOP;
  PERFORM set_config('app.skip_transitions', 'off', true);

  -- The guard still refuses a status that issues use, so nothing is left without one.
  DELETE FROM public.task_statuses WHERE project_id = p_project_id AND NOT (id = ANY (kept));

  PERFORM set_config('app.workflow_saving', 'off', true);
END;
$$;

-- Done now means the done category: the sprint report and what moves on completion.
CREATE OR REPLACE FUNCTION public.complete_task_sprint(p_sprint_id BIGINT, p_move_to BIGINT DEFAULT NULL)
RETURNS public.task_sprints
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  s public.task_sprints;
  stranded INTEGER;
BEGIN
  IF NOT public.app_is_active_employee() THEN
    RAISE EXCEPTION 'Only active employees can complete a sprint';
  END IF;

  SELECT * INTO s FROM public.task_sprints WHERE id = p_sprint_id FOR UPDATE;
  IF s.id IS NULL THEN
    RAISE EXCEPTION 'Sprint not found';
  END IF;
  IF s.state <> 'active' THEN
    RAISE EXCEPTION 'Only the active sprint can be completed';
  END IF;
  IF p_move_to IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.task_sprints
    WHERE id = p_move_to AND project_id = s.project_id AND state = 'future'
  ) THEN
    RAISE EXCEPTION 'Open issues can only move to a future sprint of this project';
  END IF;
  -- A sub-task always sits in its parent's sprint, so an open sub-task under a done
  -- parent would be stranded in the closed sprint, on no board and in no backlog.
  SELECT count(*) INTO stranded
  FROM public.tasks sub
  JOIN public.tasks parent ON parent.id = sub.parent_id
  WHERE sub.sprint_id = s.id AND sub.type = 'subtask'
    AND NOT public.task_status_is_done(sub.project_id, sub.status)
    AND public.task_status_is_done(parent.project_id, parent.status);
  IF stranded > 0 THEN
    RAISE EXCEPTION '% open sub-task(s) belong to issues already marked Done. Finish them or reopen their parent first.', stranded;
  END IF;

  UPDATE public.task_sprints
  SET state = 'closed',
      completed_at = now(),
      completed_points = (
        SELECT COALESCE(SUM(estimate), 0) FROM public.tasks
        WHERE sprint_id = s.id AND type NOT IN ('epic', 'subtask')
          AND public.task_status_is_done(project_id, status)
      )
  WHERE id = s.id
  RETURNING * INTO s;

  UPDATE public.tasks SET sprint_id = p_move_to
  WHERE sprint_id = s.id AND type <> 'subtask' AND NOT public.task_status_is_done(project_id, status);

  RETURN s;
END;
$$;

-- Status notifications carry the status's name, so the bell reads "moved to QA".
CREATE OR REPLACE FUNCTION public.tasks_notify()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  me public.employees := public.app_current_employee();
  w RECORD;
  status_name TEXT;
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM private.task_watch(NEW.id, me.id);
    PERFORM private.task_watch(NEW.id, NEW.reporter_id);
    PERFORM private.task_watch(NEW.id, NEW.assignee_id);
    PERFORM private.task_notify(NEW.assignee_id, NEW.id, 'assigned', NEW.title);
    RETURN NULL;
  END IF;

  IF NEW.assignee_id IS DISTINCT FROM OLD.assignee_id AND NEW.assignee_id IS NOT NULL THEN
    PERFORM private.task_watch(NEW.id, NEW.assignee_id);
    PERFORM private.task_notify(NEW.assignee_id, NEW.id, 'assigned', NEW.title);
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    SELECT name INTO status_name FROM public.task_statuses WHERE project_id = NEW.project_id AND key = NEW.status;
    FOR w IN SELECT employee_id FROM public.task_watchers WHERE task_id = NEW.id LOOP
      IF w.employee_id IS DISTINCT FROM NEW.assignee_id OR NEW.assignee_id IS NOT DISTINCT FROM OLD.assignee_id THEN
        PERFORM private.task_notify(w.employee_id, NEW.id, 'status', COALESCE(status_name, NEW.status));
      END IF;
    END LOOP;
  END IF;
  RETURN NULL;
END;
$$;

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Saved filters
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.task_filters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  owner_id BIGINT NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 60),
  query TEXT NOT NULL CHECK (length(query) <= 2000),
  shared BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS task_filters_project_idx ON public.task_filters (project_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Policies
