-- JIRA-STYLE ISSUES, PART 2
-- On top of 20261019125521_jira_issues.sql (applied). Adds: flags, time tracking with
-- work logs, releases (fix versions), Kanban boards with WIP limits, watchers,
-- @mentions and in-app notifications, and attachments.
--
-- Everything is additive. New rules, on top of the earlier ones:
--   * Releases          -> any active employee creates, edits and releases them; admins or
--                          the creator delete one
--   * Work logs         -> any active employee logs their own time; the author edits or
--                          deletes it, admins delete any
--   * Watchers          -> you watch or unwatch for yourself; admins for anyone
--   * Notifications     -> written only by the triggers below; you read yours and mark
--                          them read, nothing else
--   * Attachments       -> any active employee uploads and reads; the uploader or an admin
--                          deletes

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Projects: board mode and WIP limits
-- ─────────────────────────────────────────────────────────────────────────────
-- board_mode 'kanban' shows every open issue on the board with no sprints. wip_limits is
-- {"in_progress": 4, "review": 3}: the most issues a column should hold.

ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS board_mode TEXT NOT NULL DEFAULT 'scrum',
  ADD COLUMN IF NOT EXISTS wip_limits JSONB NOT NULL DEFAULT '{}'::jsonb;

ALTER TABLE public.projects DROP CONSTRAINT IF EXISTS projects_board_mode_check;
ALTER TABLE public.projects ADD CONSTRAINT projects_board_mode_check
  CHECK (board_mode IN ('scrum', 'kanban'));

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Releases (fix versions)
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.task_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  description TEXT,
  start_date DATE,
  release_date DATE,
  status TEXT NOT NULL DEFAULT 'unreleased' CHECK (status IN ('unreleased', 'released', 'archived')),
  released_at TIMESTAMPTZ,
  sort_order DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_by TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (project_id, name)
);

CREATE INDEX IF NOT EXISTS task_versions_project_id_idx ON public.task_versions (project_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Issues: flag, time tracking, fix version
-- ─────────────────────────────────────────────────────────────────────────────
-- Times are whole minutes. time_spent_min is the sum of the issue's work logs, kept by
-- the trigger below; remaining_estimate_min goes down as time is logged, as in Jira.

ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS flagged BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS original_estimate_min INTEGER,
  ADD COLUMN IF NOT EXISTS remaining_estimate_min INTEGER,
  ADD COLUMN IF NOT EXISTS time_spent_min INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS fix_version_id BIGINT REFERENCES public.task_versions(id) ON DELETE SET NULL;

ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_time_fields_check;
ALTER TABLE public.tasks ADD CONSTRAINT tasks_time_fields_check CHECK (
  (original_estimate_min IS NULL OR original_estimate_min >= 0)
  AND (remaining_estimate_min IS NULL OR remaining_estimate_min >= 0)
  AND time_spent_min >= 0
);

CREATE INDEX IF NOT EXISTS tasks_fix_version_id_idx ON public.tasks (fix_version_id);

-- A fix version belongs to one project, so an issue can only take one of its own.
CREATE OR REPLACE FUNCTION public.tasks_check_version()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NEW.fix_version_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.task_versions v WHERE v.id = NEW.fix_version_id AND v.project_id = NEW.project_id
  ) THEN
    RAISE EXCEPTION 'That release belongs to a different project';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS tasks_check_version ON public.tasks;
CREATE TRIGGER tasks_check_version
  BEFORE INSERT OR UPDATE OF fix_version_id, project_id ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.tasks_check_version();

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. Work logs
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.task_worklogs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  employee_id BIGINT REFERENCES public.employees(id) ON DELETE SET NULL,
  author_email TEXT NOT NULL,
  author_name TEXT,
  minutes INTEGER NOT NULL CHECK (minutes > 0 AND minutes <= 24 * 60),
  work_date DATE NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Kathmandu')::date,
  note TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS task_worklogs_task_id_idx ON public.task_worklogs (task_id);
CREATE INDEX IF NOT EXISTS task_worklogs_employee_date_idx ON public.task_worklogs (employee_id, work_date);

-- Who logged it comes from the session, not the request.
CREATE OR REPLACE FUNCTION public.task_worklogs_before_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  me public.employees := public.app_current_employee();
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.employee_id := COALESCE(me.id, NEW.employee_id);
    NEW.author_name := COALESCE(me.name, NEW.author_name);
  ELSE
    NEW.employee_id := OLD.employee_id;
    NEW.author_email := OLD.author_email;
    NEW.author_name := OLD.author_name;
    NEW.task_id := OLD.task_id;
  END IF;
  RETURN NEW;
END;
$$;

-- Keeps tasks.time_spent_min equal to the sum of the logs, and takes newly logged time
-- off the remaining estimate.
CREATE OR REPLACE FUNCTION public.task_worklogs_after_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target BIGINT := COALESCE(NEW.task_id, OLD.task_id);
  logged INTEGER := 0;
BEGIN
  IF TG_OP = 'INSERT' THEN
    logged := NEW.minutes;
  ELSIF TG_OP = 'UPDATE' THEN
    logged := NEW.minutes - OLD.minutes;
  END IF;
  UPDATE public.tasks t
  SET time_spent_min = (SELECT COALESCE(SUM(w.minutes), 0) FROM public.task_worklogs w WHERE w.task_id = target),
      remaining_estimate_min = CASE
        WHEN t.remaining_estimate_min IS NULL OR logged <= 0 THEN t.remaining_estimate_min
        ELSE GREATEST(t.remaining_estimate_min - logged, 0)
      END
  WHERE t.id = target;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS task_worklogs_before_write ON public.task_worklogs;
CREATE TRIGGER task_worklogs_before_write
  BEFORE INSERT OR UPDATE ON public.task_worklogs
  FOR EACH ROW EXECUTE FUNCTION public.task_worklogs_before_write();

DROP TRIGGER IF EXISTS task_worklogs_after_write ON public.task_worklogs;
CREATE TRIGGER task_worklogs_after_write
  AFTER INSERT OR UPDATE OR DELETE ON public.task_worklogs
  FOR EACH ROW EXECUTE FUNCTION public.task_worklogs_after_write();

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. Watchers, mentions and notifications
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.task_watchers (
  task_id BIGINT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  employee_id BIGINT NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  PRIMARY KEY (task_id, employee_id)
);

CREATE INDEX IF NOT EXISTS task_watchers_employee_id_idx ON public.task_watchers (employee_id);

-- The people a comment @mentions, by employee id. The body keeps the readable "@Name".
ALTER TABLE public.task_comments
  ADD COLUMN IF NOT EXISTS mentions BIGINT[] NOT NULL DEFAULT '{}';

CREATE TABLE IF NOT EXISTS public.task_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id BIGINT NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
  task_id BIGINT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('assigned', 'mentioned', 'commented', 'status')),
  actor_id BIGINT REFERENCES public.employees(id) ON DELETE SET NULL,
  actor_name TEXT,
  detail TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  read_at TIMESTAMPTZ,
  -- Set by /api/task-notifications once the email for an assignment or mention is sent.
  emailed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS task_notifications_recipient_idx ON public.task_notifications (recipient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS task_notifications_unemailed_idx ON public.task_notifications (created_at) WHERE emailed_at IS NULL;

-- The triggers' two helpers live in their own schema. The API only exposes `public`, and
-- no role but the owner may use `private`, so nobody can call them directly to add
-- watchers or forge "you were mentioned" rows that /api/task-notifications would email.
-- (Revoking EXECUTE in `public` would not do: in this Postgres build, calling a function
-- you lack EXECUTE on crashes the server process instead of raising an error. Lacking
-- USAGE on a schema raises a normal error.)
CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.task_watch(p_task_id BIGINT, p_employee_id BIGINT)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $$
  INSERT INTO public.task_watchers (task_id, employee_id)
  SELECT p_task_id, p_employee_id
  WHERE p_employee_id IS NOT NULL
  ON CONFLICT DO NOTHING;
$$;

-- Nobody is notified about their own action, and only active employees are notified.
CREATE OR REPLACE FUNCTION private.task_notify(p_recipient BIGINT, p_task_id BIGINT, p_kind TEXT, p_detail TEXT)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  me public.employees := public.app_current_employee();
BEGIN
  IF p_recipient IS NULL OR p_recipient IS NOT DISTINCT FROM me.id THEN
    RETURN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.employees e WHERE e.id = p_recipient AND e.status = 'active') THEN
    RETURN;
  END IF;
  INSERT INTO public.task_notifications (recipient_id, task_id, kind, actor_id, actor_name, detail)
  VALUES (p_recipient, p_task_id, p_kind, me.id, me.name, left(p_detail, 200));
END;
$$;

CREATE OR REPLACE FUNCTION public.tasks_notify()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  me public.employees := public.app_current_employee();
  w RECORD;
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM private.task_watch(NEW.id, me.id);
    PERFORM private.task_watch(NEW.id, NEW.reporter_id);
    PERFORM private.task_watch(NEW.id, NEW.assignee_id);
    PERFORM private.task_notify(NEW.assignee_id, NEW.id, 'assigned', NEW.title);
    RETURN NULL;
  END IF;

  IF NEW.assignee_id IS DISTINCT FROM OLD.assignee_id AND NEW.assignee_id IS NOT NULL THEN
    PERFORM private.task_watch(NEW.id, NEW.assignee_id);
    PERFORM private.task_notify(NEW.assignee_id, NEW.id, 'assigned', NEW.title);
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    FOR w IN SELECT employee_id FROM public.task_watchers WHERE task_id = NEW.id LOOP
      -- The new assignee has just been told; one notification per change is enough.
      IF w.employee_id IS DISTINCT FROM NEW.assignee_id OR NEW.assignee_id IS NOT DISTINCT FROM OLD.assignee_id THEN
        PERFORM private.task_notify(w.employee_id, NEW.id, 'status', NEW.status);
      END IF;
    END LOOP;
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS tasks_notify ON public.tasks;
CREATE TRIGGER tasks_notify
  AFTER INSERT OR UPDATE OF assignee_id, status ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.tasks_notify();

-- A comment: the author starts watching, everyone @mentioned is told (and watches),
-- every other watcher gets a "commented".
CREATE OR REPLACE FUNCTION public.task_comments_notify()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  me public.employees := public.app_current_employee();
  m BIGINT;
  w RECORD;
BEGIN
  PERFORM private.task_watch(NEW.task_id, me.id);
  FOREACH m IN ARRAY COALESCE(NEW.mentions, '{}') LOOP
    PERFORM private.task_watch(NEW.task_id, m);
    PERFORM private.task_notify(m, NEW.task_id, 'mentioned', NEW.body);
  END LOOP;
  FOR w IN SELECT employee_id FROM public.task_watchers WHERE task_id = NEW.task_id LOOP
    IF NOT (w.employee_id = ANY (COALESCE(NEW.mentions, '{}'))) THEN
      PERFORM private.task_notify(w.employee_id, NEW.task_id, 'commented', NEW.body);
    END IF;
  END LOOP;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS task_comments_notify ON public.task_comments;
CREATE TRIGGER task_comments_notify
  AFTER INSERT ON public.task_comments
  FOR EACH ROW EXECUTE FUNCTION public.task_comments_notify();

-- Existing issues: reporters and assignees start out watching, as new issues do.
INSERT INTO public.task_watchers (task_id, employee_id)
SELECT id, reporter_id FROM public.tasks WHERE reporter_id IS NOT NULL
ON CONFLICT DO NOTHING;
INSERT INTO public.task_watchers (task_id, employee_id)
SELECT id, assignee_id FROM public.tasks WHERE assignee_id IS NOT NULL
ON CONFLICT DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────
-- 6. Attachments
-- ─────────────────────────────────────────────────────────────────────────────
-- The file lives in the private "task-attachments" storage bucket at `path`; this row
-- is its listing on the issue. Downloads go through short-lived signed URLs.

CREATE TABLE IF NOT EXISTS public.task_attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  path TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  size_bytes BIGINT,
  mime_type TEXT,
  uploaded_by TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS task_attachments_task_id_idx ON public.task_attachments (task_id);

-- Storage lives in Supabase's own schema, which a bare local Postgres doesn't have, so
-- the bucket and its policies are only created where storage exists.
DO $$
BEGIN
  IF to_regclass('storage.buckets') IS NULL THEN
    RAISE NOTICE 'storage schema not present; skipping the task-attachments bucket';
    RETURN;
  END IF;

  INSERT INTO storage.buckets (id, name, public, file_size_limit)
  VALUES ('task-attachments', 'task-attachments', false, 10485760)
  ON CONFLICT (id) DO NOTHING;

  EXECUTE 'DROP POLICY IF EXISTS "Employees read task attachments" ON storage.objects';
  EXECUTE 'DROP POLICY IF EXISTS "Employees upload task attachments" ON storage.objects';
  EXECUTE 'DROP POLICY IF EXISTS "Uploader or admin delete task attachments" ON storage.objects';

  EXECUTE $p$CREATE POLICY "Employees read task attachments" ON storage.objects
    FOR SELECT TO authenticated
    USING (bucket_id = 'task-attachments' AND public.app_is_active_employee())$p$;
  EXECUTE $p$CREATE POLICY "Employees upload task attachments" ON storage.objects
    FOR INSERT TO authenticated
    WITH CHECK (bucket_id = 'task-attachments' AND public.app_is_active_employee())$p$;
  EXECUTE $p$CREATE POLICY "Uploader or admin delete task attachments" ON storage.objects
    FOR DELETE TO authenticated
    USING (bucket_id = 'task-attachments' AND (public.app_is_admin() OR owner_id = (SELECT auth.uid())::text))$p$;
END;
$$;

