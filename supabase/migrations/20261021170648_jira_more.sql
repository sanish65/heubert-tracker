-- Releases
DROP POLICY IF EXISTS "Employees read releases" ON public.task_versions;
DROP POLICY IF EXISTS "Employees create releases" ON public.task_versions;
DROP POLICY IF EXISTS "Employees update releases" ON public.task_versions;
DROP POLICY IF EXISTS "Admins or creator delete releases" ON public.task_versions;
CREATE POLICY "Employees read releases" ON public.task_versions
  FOR SELECT USING (public.app_is_active_employee());
CREATE POLICY "Employees create releases" ON public.task_versions
  FOR INSERT WITH CHECK (public.app_is_active_employee() AND lower(created_by) = lower(auth.jwt() ->> 'email'));
CREATE POLICY "Employees update releases" ON public.task_versions
  FOR UPDATE USING (public.app_is_active_employee()) WITH CHECK (public.app_is_active_employee());
CREATE POLICY "Admins or creator delete releases" ON public.task_versions
  FOR DELETE USING (public.app_is_admin() OR lower(created_by) = lower(auth.jwt() ->> 'email'));

-- Work logs
DROP POLICY IF EXISTS "Employees read work logs" ON public.task_worklogs;
DROP POLICY IF EXISTS "Employees log own work" ON public.task_worklogs;
DROP POLICY IF EXISTS "Author edits work log" ON public.task_worklogs;
DROP POLICY IF EXISTS "Author or admin delete work log" ON public.task_worklogs;
CREATE POLICY "Employees read work logs" ON public.task_worklogs
  FOR SELECT USING (public.app_is_active_employee());
CREATE POLICY "Employees log own work" ON public.task_worklogs
  FOR INSERT WITH CHECK (public.app_is_active_employee() AND lower(author_email) = lower(auth.jwt() ->> 'email'));
CREATE POLICY "Author edits work log" ON public.task_worklogs
  FOR UPDATE USING (lower(author_email) = lower(auth.jwt() ->> 'email'))
  WITH CHECK (lower(author_email) = lower(auth.jwt() ->> 'email'));
CREATE POLICY "Author or admin delete work log" ON public.task_worklogs
  FOR DELETE USING (public.app_is_admin() OR lower(author_email) = lower(auth.jwt() ->> 'email'));

-- Watchers
DROP POLICY IF EXISTS "Employees read watchers" ON public.task_watchers;
DROP POLICY IF EXISTS "Watch for yourself" ON public.task_watchers;
DROP POLICY IF EXISTS "Unwatch for yourself" ON public.task_watchers;
CREATE POLICY "Employees read watchers" ON public.task_watchers
  FOR SELECT USING (public.app_is_active_employee());
CREATE POLICY "Watch for yourself" ON public.task_watchers
  FOR INSERT WITH CHECK (
    public.app_is_active_employee()
    AND (employee_id = (public.app_current_employee()).id OR public.app_is_admin())
  );
CREATE POLICY "Unwatch for yourself" ON public.task_watchers
  FOR DELETE USING (employee_id = (public.app_current_employee()).id OR public.app_is_admin());

-- Notifications: your own only; the one change allowed is marking them read.
DROP POLICY IF EXISTS "Read own notifications" ON public.task_notifications;
DROP POLICY IF EXISTS "Mark own notifications read" ON public.task_notifications;
CREATE POLICY "Read own notifications" ON public.task_notifications
  FOR SELECT USING (recipient_id = (public.app_current_employee()).id);
CREATE POLICY "Mark own notifications read" ON public.task_notifications
  FOR UPDATE USING (recipient_id = (public.app_current_employee()).id)
  WITH CHECK (recipient_id = (public.app_current_employee()).id);
REVOKE UPDATE ON public.task_notifications FROM anon, authenticated;
GRANT UPDATE (read_at) ON public.task_notifications TO authenticated;

-- Attachments
DROP POLICY IF EXISTS "Employees read attachments" ON public.task_attachments;
DROP POLICY IF EXISTS "Employees add attachments" ON public.task_attachments;
DROP POLICY IF EXISTS "Uploader or admin delete attachments" ON public.task_attachments;
CREATE POLICY "Employees read attachments" ON public.task_attachments
  FOR SELECT USING (public.app_is_active_employee());
CREATE POLICY "Employees add attachments" ON public.task_attachments
  FOR INSERT WITH CHECK (public.app_is_active_employee() AND lower(uploaded_by) = lower(auth.jwt() ->> 'email'));
CREATE POLICY "Uploader or admin delete attachments" ON public.task_attachments
  FOR DELETE USING (public.app_is_admin() OR lower(uploaded_by) = lower(auth.jwt() ->> 'email'));
