-- TASK BOARD (KANBAN) SCHEMA
-- Uses the app_current_employee() / app_is_admin() helpers that came from
-- scripts/admin-write-permissions-rls.sql and now live in the baseline migration.
--
-- Who may do what:
--   * Read                      -> active employees only. Tasks carry client work, so
--                                  unlike the older tables they are not world-readable.
--   * Create a task / comment   -> any active employee, recorded as themselves
--   * Edit / move a task        -> any active employee (it is a shared team board)
--   * Delete a task / comment   -> admins, or whoever created it

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Tables
-- ─────────────────────────────────────────────────────────────────────────────

-- project_id ON DELETE SET NULL: deleting a project keeps its task history; the tasks
-- move to "No project". assignee_id likewise survives the employee being removed.
-- sort_order is a float so a card dropped between two others takes the midpoint and
-- nothing else in the column has to be renumbered.
CREATE TABLE IF NOT EXISTS tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT REFERENCES projects(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  description TEXT,
  status TEXT NOT NULL DEFAULT 'todo'
    CHECK (status IN ('backlog', 'todo', 'in_progress', 'review', 'done')),
  priority TEXT NOT NULL DEFAULT 'medium'
    CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
  assignee_id BIGINT REFERENCES employees(id) ON DELETE SET NULL,
  estimate NUMERIC,
  due_date DATE,
  labels TEXT[] NOT NULL DEFAULT '{}',
  external_url TEXT,
  sort_order DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_by TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  completed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS task_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  author_email TEXT NOT NULL,
  author_name TEXT,
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS tasks_status_sort_idx ON tasks(status, sort_order);
CREATE INDEX IF NOT EXISTS tasks_project_id_idx ON tasks(project_id);
CREATE INDEX IF NOT EXISTS tasks_assignee_id_idx ON tasks(assignee_id);
CREATE INDEX IF NOT EXISTS task_comments_task_id_idx ON task_comments(task_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Who counts as an active employee
-- ─────────────────────────────────────────────────────────────────────────────
-- Same lookup the app uses at sign-in (AppContext verifyEmployeeAccess): a former
-- employee who still has a Google session must not keep reading the board.

CREATE OR REPLACE FUNCTION public.app_is_active_employee()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT COALESCE((public.app_current_employee()).status = 'active', false);
$$;

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Policies
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE task_comments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Employees read tasks" ON tasks;
DROP POLICY IF EXISTS "Employees create tasks" ON tasks;
DROP POLICY IF EXISTS "Employees update tasks" ON tasks;
DROP POLICY IF EXISTS "Admins or creator delete tasks" ON tasks;

CREATE POLICY "Employees read tasks" ON tasks
  FOR SELECT USING (public.app_is_active_employee());

-- created_by must be the caller, so nobody can file a task in a colleague's name and
-- thereby hand them (or keep for themselves) the right to delete it.
CREATE POLICY "Employees create tasks" ON tasks
  FOR INSERT WITH CHECK (
    public.app_is_active_employee()
    AND lower(created_by) = lower(auth.jwt() ->> 'email')
  );

CREATE POLICY "Employees update tasks" ON tasks
  FOR UPDATE USING (public.app_is_active_employee())
  WITH CHECK (public.app_is_active_employee());

CREATE POLICY "Admins or creator delete tasks" ON tasks
  FOR DELETE USING (
    public.app_is_admin()
    OR lower(created_by) = lower(auth.jwt() ->> 'email')
  );

DROP POLICY IF EXISTS "Employees read task comments" ON task_comments;
DROP POLICY IF EXISTS "Employees create task comments" ON task_comments;
DROP POLICY IF EXISTS "Admins or author delete task comments" ON task_comments;

CREATE POLICY "Employees read task comments" ON task_comments
  FOR SELECT USING (public.app_is_active_employee());

CREATE POLICY "Employees create task comments" ON task_comments
  FOR INSERT WITH CHECK (
    public.app_is_active_employee()
    AND lower(author_email) = lower(auth.jwt() ->> 'email')
  );

-- No UPDATE policy: comments are not editable, only deletable.
CREATE POLICY "Admins or author delete task comments" ON task_comments
  FOR DELETE USING (
    public.app_is_admin()
    OR lower(author_email) = lower(auth.jwt() ->> 'email')
  );

