CREATE OR REPLACE FUNCTION "public"."app_current_employee"() RETURNS "public"."employees"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  SELECT e.*
  FROM public.employees e
  WHERE lower(e.work_email) = lower(auth.jwt() ->> 'email')
     OR lower(e.personal_email) = lower(auth.jwt() ->> 'email')
  LIMIT 1;
$$;


ALTER FUNCTION "public"."app_current_employee"() OWNER TO "postgres";


