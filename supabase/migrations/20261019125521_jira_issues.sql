  FOR SELECT USING (public.app_is_active_employee());

CREATE POLICY "Employees create sprints" ON public.task_sprints
  FOR INSERT WITH CHECK (
    public.app_is_active_employee()
    AND lower(created_by) = lower(auth.jwt() ->> 'email')
  );

CREATE POLICY "Employees update sprints" ON public.task_sprints
  FOR UPDATE USING (public.app_is_active_employee())
  WITH CHECK (public.app_is_active_employee());

-- Deleting a sprint sends its issues back to the backlog (sprint_id ON DELETE SET NULL).
CREATE POLICY "Admins or creator delete sprints" ON public.task_sprints
  FOR DELETE USING (
    public.app_is_admin()
    OR lower(created_by) = lower(auth.jwt() ->> 'email')
  );

-- No insert, update or delete policy: only tasks_after_write writes history.
