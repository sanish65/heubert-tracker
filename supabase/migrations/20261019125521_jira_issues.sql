-- JIRA-STYLE ISSUES
-- Builds on 20261019122033_task_board.sql (already applied). Turns its plain tasks into
-- Jira-style issues: per-project keys and numbers (HTT-12), issue types with epics and
-- sub-tasks, sprints, issue links and a change history.
--
-- Everything here is additive except two value renames on tasks, made before the new
-- checks go on: status 'backlog' -> 'todo' (in a sprint model the backlog is "not in a
-- sprint", not a status) and priority 'urgent' -> 'highest' (Jira's five levels).
--
-- Who may do what, on top of the task_board rules:
--   * Sprints        -> any active employee creates, edits, starts and completes them;
--                       admins or the creator delete one
--   * Issue links    -> any active employee adds or removes them
--   * Change history -> written only by the trigger below; employees read it

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Project issue keys
-- ─────────────────────────────────────────────────────────────────────────────
-- issue_key is the HTT in HTT-12. issue_seq is the last number handed out, so numbers
-- are never reused even after an issue is deleted.

ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS issue_key TEXT,
  ADD COLUMN IF NOT EXISTS issue_seq INTEGER NOT NULL DEFAULT 0;

ALTER TABLE public.projects DROP CONSTRAINT IF EXISTS projects_issue_key_format;
ALTER TABLE public.projects ADD CONSTRAINT projects_issue_key_format
  CHECK (issue_key IS NULL OR issue_key ~ '^[A-Z][A-Z0-9]{1,9}$');

CREATE UNIQUE INDEX IF NOT EXISTS projects_issue_key_unique ON public.projects (issue_key);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Sprints (one board per project, like a Jira Scrum board)
-- ─────────────────────────────────────────────────────────────────────────────
-- Separate from the older company-wide `sprints` table, which Capacity and the mobile
-- app read and which has no project.

CREATE TABLE IF NOT EXISTS public.task_sprints (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  goal TEXT,
  state TEXT NOT NULL DEFAULT 'future' CHECK (state IN ('future', 'active', 'closed')),
  start_date DATE,
  end_date DATE,
  -- Snapshots for the velocity chart: points in the sprint when it started, and points
  -- done when it closed. Later scope changes don't rewrite history.
  committed_points NUMERIC,
  completed_points NUMERIC,
  started_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  sort_order DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_by TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS task_sprints_project_id_idx ON public.task_sprints (project_id);
CREATE UNIQUE INDEX IF NOT EXISTS task_sprints_one_active_per_project
  ON public.task_sprints (project_id) WHERE state = 'active';

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Tasks become issues
-- ─────────────────────────────────────────────────────────────────────────────

-- The old checks come off before the renames: 'highest' isn't allowed by the old
-- priority check, so renaming first would abort the migration on any 'urgent' task.
ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_status_check;
ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_priority_check;

UPDATE public.tasks SET status = 'todo' WHERE status = 'backlog';
UPDATE public.tasks SET priority = 'highest' WHERE priority = 'urgent';

ALTER TABLE public.tasks ADD CONSTRAINT tasks_status_check
  CHECK (status IN ('todo', 'in_progress', 'review', 'done'));

ALTER TABLE public.tasks ADD CONSTRAINT tasks_priority_check
  CHECK (priority IN ('highest', 'high', 'medium', 'low', 'lowest'));

ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS number INTEGER,
  ADD COLUMN IF NOT EXISTS type TEXT NOT NULL DEFAULT 'task',
  ADD COLUMN IF NOT EXISTS parent_id BIGINT REFERENCES public.tasks(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS sprint_id BIGINT REFERENCES public.task_sprints(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS reporter_id BIGINT REFERENCES public.employees(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS epic_color TEXT;

ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_type_check;
ALTER TABLE public.tasks ADD CONSTRAINT tasks_type_check
  CHECK (type IN ('epic', 'story', 'task', 'bug', 'subtask'));

ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_not_own_parent;
ALTER TABLE public.tasks ADD CONSTRAINT tasks_not_own_parent
  CHECK (parent_id IS NULL OR parent_id <> id);

ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_project_number_unique;
ALTER TABLE public.tasks ADD CONSTRAINT tasks_project_number_unique UNIQUE (project_id, number);

-- An issue belongs to its project for life, so deleting the project deletes its issues
-- (the task_board migration had SET NULL, from when a project was optional).
ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_project_id_fkey;
ALTER TABLE public.tasks ADD CONSTRAINT tasks_project_id_fkey
  FOREIGN KEY (project_id) REFERENCES public.projects(id) ON DELETE CASCADE;

-- Every new issue needs a project. NOT VALID leaves any task made on the first board
-- without one alone; the app lists those so someone can file each into a project.
ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_project_required;
ALTER TABLE public.tasks ADD CONSTRAINT tasks_project_required
  CHECK (project_id IS NOT NULL) NOT VALID;

CREATE INDEX IF NOT EXISTS tasks_sprint_id_idx ON public.tasks (sprint_id);
CREATE INDEX IF NOT EXISTS tasks_parent_id_idx ON public.tasks (parent_id);

-- Number the tasks that already exist, oldest first, and move each project's counter
-- past them. Done before the triggers below exist, so it writes no history.
WITH numbered AS (
  SELECT id, row_number() OVER (PARTITION BY project_id ORDER BY created_at, id) AS n
  FROM public.tasks
  WHERE project_id IS NOT NULL AND number IS NULL
)
UPDATE public.tasks t SET number = numbered.n FROM numbered WHERE t.id = numbered.id;

UPDATE public.projects p
SET issue_seq = GREATEST(p.issue_seq, s.max_number)
FROM (
  SELECT project_id, MAX(number) AS max_number
  FROM public.tasks
  WHERE project_id IS NOT NULL
  GROUP BY project_id
) s
WHERE p.id = s.project_id;

UPDATE public.tasks t
SET reporter_id = e.id
FROM public.employees e
WHERE t.reporter_id IS NULL
  AND t.created_by IS NOT NULL
  AND (lower(e.work_email) = lower(t.created_by) OR lower(e.personal_email) = lower(t.created_by));

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. Change history and issue links
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.task_activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  actor_email TEXT,
  actor_name TEXT,
  field TEXT NOT NULL,
  old_value TEXT,
  new_value TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS task_activity_task_id_idx ON public.task_activity (task_id, created_at);

-- One row per relationship, stored from the source's side: "A blocks B" is
-- (A, B, 'blocks') and B shows it as "is blocked by A".
CREATE TABLE IF NOT EXISTS public.task_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id BIGINT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  target_id BIGINT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  link_type TEXT NOT NULL CHECK (link_type IN ('blocks', 'relates', 'duplicates')),
  created_by TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (source_id, target_id, link_type),
  CHECK (source_id <> target_id)
);

CREATE INDEX IF NOT EXISTS task_links_source_id_idx ON public.task_links (source_id);
CREATE INDEX IF NOT EXISTS task_links_target_id_idx ON public.task_links (target_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. Issue rules, enforced on every write
-- ─────────────────────────────────────────────────────────────────────────────
-- In the database rather than the app, so the mobile app, a second tab or a direct API
-- call can't number an issue twice, put a sub-task under an epic or lose its history.
--
-- SECURITY DEFINER because numbering bumps projects.issue_seq, and history rows are
-- written into a table that has no insert policy at all.

CREATE OR REPLACE FUNCTION public.tasks_before_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  parent public.tasks;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF OLD.project_id IS NOT NULL AND NEW.project_id IS DISTINCT FROM OLD.project_id THEN
      RAISE EXCEPTION 'An issue cannot move to another project';
    END IF;
    IF OLD.number IS NOT NULL AND NEW.number IS DISTINCT FROM OLD.number THEN
      RAISE EXCEPTION 'Issue numbers cannot be changed';
    END IF;
    IF NEW.type IS DISTINCT FROM OLD.type THEN
      IF OLD.type = 'epic' AND EXISTS (SELECT 1 FROM public.tasks WHERE parent_id = OLD.id) THEN
        RAISE EXCEPTION 'Move the issues out of this epic before changing its type';
      END IF;
      IF NEW.type IN ('epic', 'subtask')
         AND EXISTS (SELECT 1 FROM public.tasks WHERE parent_id = OLD.id AND type = 'subtask') THEN
        RAISE EXCEPTION 'Remove this issue''s sub-tasks before changing its type';
      END IF;
    END IF;
    NEW.updated_at := now();
  END IF;

  -- A number is handed out the first time an issue has a project: on create, or when a
  -- task from the first board is filed into one.
  IF NEW.project_id IS NOT NULL AND NEW.number IS NULL THEN
    UPDATE public.projects
    SET issue_seq = issue_seq + 1
    WHERE id = NEW.project_id
    RETURNING issue_seq INTO NEW.number;
    IF NEW.number IS NULL THEN
      RAISE EXCEPTION 'Project % does not exist', NEW.project_id;
    END IF;
  END IF;

  -- Hierarchy: epic > story / task / bug > sub-task. Epics live outside sprints, and a
  -- sub-task is always in its parent's sprint.
  IF NEW.type = 'epic' THEN
    IF NEW.parent_id IS NOT NULL THEN
      RAISE EXCEPTION 'An epic cannot have a parent';
    END IF;
    NEW.sprint_id := NULL;
  ELSIF NEW.parent_id IS NOT NULL THEN
    SELECT * INTO parent FROM public.tasks WHERE id = NEW.parent_id;
    IF parent.id IS NULL THEN
      RAISE EXCEPTION 'Parent issue not found';
    END IF;
    IF parent.project_id IS DISTINCT FROM NEW.project_id THEN
      RAISE EXCEPTION 'The parent issue must be in the same project';
    END IF;
    IF NEW.type = 'subtask' THEN
      IF parent.type IN ('epic', 'subtask') THEN
        RAISE EXCEPTION 'A sub-task belongs under a story, task or bug';
      END IF;
      NEW.sprint_id := parent.sprint_id;
    ELSIF parent.type <> 'epic' THEN
      RAISE EXCEPTION 'Only an epic can be the parent of a %', NEW.type;
    END IF;
  ELSIF NEW.type = 'subtask' THEN
    RAISE EXCEPTION 'A sub-task needs a parent issue';
  END IF;

  IF NEW.sprint_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.task_sprints s
    WHERE s.id = NEW.sprint_id AND s.project_id = NEW.project_id
  ) THEN
    RAISE EXCEPTION 'That sprint belongs to a different project';
  END IF;

  -- completed_at follows the Done column: stamped on the way in, kept while it stays,
  -- cleared when the issue is reopened. The burndown chart reads it.
  IF NEW.status = 'done' THEN
    IF TG_OP = 'UPDATE' AND OLD.status = 'done' THEN
      NEW.completed_at := COALESCE(OLD.completed_at, now());
    ELSE
      NEW.completed_at := now();
    END IF;
  ELSE
    NEW.completed_at := NULL;
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.tasks_after_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor_email TEXT := auth.jwt() ->> 'email';
  actor_name TEXT := public.app_employee_name();
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field)
    VALUES (NEW.id, actor_email, actor_name, 'created');
    RETURN NULL;
  END IF;

  -- Sub-tasks travel with their parent between sprints.
  IF NEW.sprint_id IS DISTINCT FROM OLD.sprint_id AND NEW.type <> 'subtask' THEN
    UPDATE public.tasks SET sprint_id = NEW.sprint_id
    WHERE parent_id = NEW.id AND type = 'subtask';
  END IF;

  -- History stores raw values (ids for people, sprints and parents); the app turns
  -- them into names when it shows them.
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'status', OLD.status, NEW.status);
  END IF;
  IF NEW.assignee_id IS DISTINCT FROM OLD.assignee_id THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'assignee_id', OLD.assignee_id::text, NEW.assignee_id::text);
  END IF;
  IF NEW.reporter_id IS DISTINCT FROM OLD.reporter_id THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'reporter_id', OLD.reporter_id::text, NEW.reporter_id::text);
  END IF;
  IF NEW.priority IS DISTINCT FROM OLD.priority THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'priority', OLD.priority, NEW.priority);
  END IF;
  IF NEW.type IS DISTINCT FROM OLD.type THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'type', OLD.type, NEW.type);
  END IF;
  IF NEW.sprint_id IS DISTINCT FROM OLD.sprint_id THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'sprint_id', OLD.sprint_id::text, NEW.sprint_id::text);
  END IF;
  IF NEW.parent_id IS DISTINCT FROM OLD.parent_id THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'parent_id', OLD.parent_id::text, NEW.parent_id::text);
  END IF;
  IF NEW.project_id IS DISTINCT FROM OLD.project_id THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'project_id', OLD.project_id::text, NEW.project_id::text);
  END IF;
  IF NEW.estimate IS DISTINCT FROM OLD.estimate THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'estimate', OLD.estimate::text, NEW.estimate::text);
  END IF;
  IF NEW.due_date IS DISTINCT FROM OLD.due_date THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'due_date', OLD.due_date::text, NEW.due_date::text);
  END IF;
  IF NEW.title IS DISTINCT FROM OLD.title THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'title', OLD.title, NEW.title);
  END IF;
  IF NEW.labels IS DISTINCT FROM OLD.labels THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'labels',
            array_to_string(OLD.labels, ', '), array_to_string(NEW.labels, ', '));
  END IF;
  IF NEW.external_url IS DISTINCT FROM OLD.external_url THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field, old_value, new_value)
    VALUES (NEW.id, actor_email, actor_name, 'external_url', OLD.external_url, NEW.external_url);
  END IF;
  -- Descriptions can be long; the history only records that it changed.
  IF NEW.description IS DISTINCT FROM OLD.description THEN
    INSERT INTO public.task_activity (task_id, actor_email, actor_name, field)
    VALUES (NEW.id, actor_email, actor_name, 'description');
  END IF;

  RETURN NULL;
END;
$$;

-- Sub-tasks mean nothing without their parent. Children of a deleted epic stay, with
-- their epic cleared by the parent_id foreign key.
CREATE OR REPLACE FUNCTION public.tasks_before_delete()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  DELETE FROM public.tasks WHERE parent_id = OLD.id AND type = 'subtask';
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS tasks_before_write ON public.tasks;
CREATE TRIGGER tasks_before_write
  BEFORE INSERT OR UPDATE ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.tasks_before_write();

DROP TRIGGER IF EXISTS tasks_after_write ON public.tasks;
CREATE TRIGGER tasks_after_write
  AFTER INSERT OR UPDATE ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.tasks_after_write();

DROP TRIGGER IF EXISTS tasks_before_delete ON public.tasks;
CREATE TRIGGER tasks_before_delete
  BEFORE DELETE ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.tasks_before_delete();

-- ─────────────────────────────────────────────────────────────────────────────
-- 6. Starting and completing a sprint
-- ─────────────────────────────────────────────────────────────────────────────
-- Each is several writes that must happen together, so they are functions the app calls
-- in one round trip. SECURITY INVOKER: the caller's own row level security applies.

CREATE OR REPLACE FUNCTION public.start_task_sprint(p_sprint_id BIGINT, p_start DATE, p_end DATE)
RETURNS public.task_sprints
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  s public.task_sprints;
BEGIN
  IF NOT public.app_is_active_employee() THEN
    RAISE EXCEPTION 'Only active employees can start a sprint';
  END IF;
  IF p_start IS NULL OR p_end IS NULL OR p_end < p_start THEN
    RAISE EXCEPTION 'A sprint needs a start date and an end date on or after it';
  END IF;

  SELECT * INTO s FROM public.task_sprints WHERE id = p_sprint_id FOR UPDATE;
  IF s.id IS NULL THEN
    RAISE EXCEPTION 'Sprint not found';
  END IF;
  IF s.state <> 'future' THEN
    RAISE EXCEPTION 'This sprint has already been started';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.task_sprints WHERE project_id = s.project_id AND state = 'active'
  ) THEN
    RAISE EXCEPTION 'Complete the active sprint before starting another';
  END IF;

  UPDATE public.task_sprints
  SET state = 'active',
      start_date = p_start,
      end_date = p_end,
      started_at = now(),
      committed_points = (
        SELECT COALESCE(SUM(estimate), 0) FROM public.tasks
        WHERE sprint_id = s.id AND type NOT IN ('epic', 'subtask')
      )
  WHERE id = s.id
  RETURNING * INTO s;

  RETURN s;
END;
$$;

-- Open issues move to p_move_to (a future sprint of the same project) or, when it is
-- null, back to the backlog. Done issues stay in the closed sprint for its report.
CREATE OR REPLACE FUNCTION public.complete_task_sprint(p_sprint_id BIGINT, p_move_to BIGINT DEFAULT NULL)
RETURNS public.task_sprints
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  s public.task_sprints;
  stranded INTEGER;
BEGIN
  IF NOT public.app_is_active_employee() THEN
    RAISE EXCEPTION 'Only active employees can complete a sprint';
  END IF;

  SELECT * INTO s FROM public.task_sprints WHERE id = p_sprint_id FOR UPDATE;
  IF s.id IS NULL THEN
    RAISE EXCEPTION 'Sprint not found';
  END IF;
  IF s.state <> 'active' THEN
    RAISE EXCEPTION 'Only the active sprint can be completed';
  END IF;
  IF p_move_to IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.task_sprints
    WHERE id = p_move_to AND project_id = s.project_id AND state = 'future'
  ) THEN
    RAISE EXCEPTION 'Open issues can only move to a future sprint of this project';
  END IF;
  -- A sub-task always sits in its parent's sprint, so an open sub-task under a done
  -- parent would be stranded in the closed sprint, on no board and in no backlog.
  -- Refuse, and say how many, so the team finishes them or reopens the parent.
  SELECT count(*) INTO stranded
  FROM public.tasks sub
  JOIN public.tasks parent ON parent.id = sub.parent_id
  WHERE sub.sprint_id = s.id AND sub.type = 'subtask' AND sub.status <> 'done' AND parent.status = 'done';
  IF stranded > 0 THEN
    RAISE EXCEPTION '% open sub-task(s) belong to issues already marked Done. Finish them or reopen their parent first.', stranded;
  END IF;

  UPDATE public.task_sprints
  SET state = 'closed',
      completed_at = now(),
      completed_points = (
        SELECT COALESCE(SUM(estimate), 0) FROM public.tasks
        WHERE sprint_id = s.id AND status = 'done' AND type NOT IN ('epic', 'subtask')
      )
  WHERE id = s.id
  RETURNING * INTO s;

  -- Sub-tasks follow their parent through tasks_after_write.
  UPDATE public.tasks SET sprint_id = p_move_to
  WHERE sprint_id = s.id AND status <> 'done' AND type <> 'subtask';

  RETURN s;
END;
$$;

